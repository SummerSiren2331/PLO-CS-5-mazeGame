/**
 * Enum to declare the type of Interactable 
 * @author Morgan Fidler
 */
public enum Interactables {
	SWORD, POTION, SPELLSCROLL, HELMET, TRAP 
	// Sword allows for an attack
	// Potion increases HP
	// SpellScroll allows visibility of a random algorithm's path
	// Helmet decreases damage
	// Trap is invisible and is auto-interacted with
}
